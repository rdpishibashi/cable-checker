COLUMNS = ['区分', '項目', '記号・語', '意味・条件', 'Excel のセル色', 'viewer の文字色']


def legend_rows():
    """「記号の説明」シートの行（COLUMNS の順）。"""
    rows = [['記号', '記号', sym, meaning, excel, viewer] for sym, meaning, excel, viewer in SYMBOL_ROWS]
    for column in C.ITEM_COLUMNS:
        for sym in C.SYMBOLS:
            if sym in ITEM_RULES[column]:
                rows.append(['項目の判定', column, sym, ITEM_RULES[column][sym], '', ''])
    rows += [['判断根拠の語', '照合明細の「判断根拠」', word, BASIS_MEANING[word], '', ''] for word in BASIS_ORDER]
    return rows
